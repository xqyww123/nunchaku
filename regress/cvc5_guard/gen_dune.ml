(* Generates the rules of this suite: every case is the same rule pair, so the
   table below is the whole of what a case is.  Edit the table, run
   [dune build @regress/cvc5_guard/runtest] and [dune promote] to refresh
   dune.inc.

   - [problem]: the .nun file to run.
   - [reply]: canned solver output replayed by fake_solver, if the case uses
     one.  A case that only exercises variable handling has none.
   - [solvers]: the --solvers argument.
   - [env]: extra environment, as VAR=VALUE; the value may contain a dune
     variable, which is expanded in the generated rule. *)

type case = {
  name : string;
  problem : string;
  reply : string option;
  solvers : string;
  env : (string * string) list;
}

let fake = "%{exe:../support/fake_solver.exe}"

(* the ordinary shape: a canned cvc5 reply for a problem, through fake_solver *)
let cvc5 ?(problem = "three.nun") name =
  { name; problem; reply = Some ("reply_" ^ name ^ ".txt");
    solvers = "cvc5"; env = [ ("NUNCHAKU_CVC5", fake) ] }

let cases =
  List.map cvc5
    [ (* 1: positive control, on the full model text *)
      "ok";
      (* 2-8: a malformed domain reply, one named cause each *)
      "bare"; "wrongty"; "atom"; "error"; "empty"; "dup"; "collide";
      (* the lexer's two error positions, in the domain reply *)
      "escape"; "unterm" ]
  @ [ (* 9: an empty variable for a solver that was requested *)
      { name = "empty_cvc5"; problem = "three.nun"; reply = None;
        solvers = "cvc5"; env = [ ("NUNCHAKU_CVC5", "") ] };
      (* 10: the same variable, for a solver that was not requested *)
      { name = "empty_cvc5_smbc"; problem = "three.nun";
        reply = Some "reply_smbc.txt"; solvers = "smbc";
        env = [ ("NUNCHAKU_CVC5", ""); ("NUNCHAKU_SMBC", fake) ] } ]

let pp_case c =
  let dep_reply = match c.reply with None -> "" | Some r -> "\n  " ^ r in
  let dep_fake =
    if List.exists (fun (_, v) -> v = fake) c.env then
      "\n  %{exe:../support/fake_solver.exe}"
    else ""
  in
  let setenv =
    List.map (fun (k, v) -> Printf.sprintf "\n    --setenv\n    \"%s=%s\"" k v) c.env
    @ (match c.reply with
       | None -> []
       | Some r -> [ Printf.sprintf "\n    --setenv\n    \"FAKE_REPLIES=%%{dep:%s}\"" r ])
    |> String.concat ""
  in
  Printf.printf
    {|
(rule
 (targets %s.out)
 (deps
  %%{exe:../support/run_case.exe}%s
  %%{exe:../../src/main/nunchaku.exe}
  %s%s)
 (action
  (with-stdout-to
   %s.out
   (run
    %%{exe:../support/run_case.exe}
    --exe
    %%{exe:../../src/main/nunchaku.exe}
    --deadline
    20%s
    --
    --solvers
    %s
    --no-color
    -j
    1
    --timeout
    5
    %%{dep:%s}))))

(rule
 (alias runtest)
 (action
  (diff %s.expected %s.out)))
|}
    c.name dep_fake c.problem dep_reply c.name setenv c.solvers c.problem c.name
    c.name

let () =
  print_string
    "; GENERATED by gen_dune.ml -- do not edit.  Add a case to the table there,\n\
     ; then `dune build @regress/cvc5_guard/runtest` and `dune promote`.\n";
  List.iter pp_case cases

(* Generates the rules of this suite.  Every case is the same rule pair, so
   there is no table here: the table is [cases.tsv], which is also what the
   README explains case by case, and this file only turns one of its rows into
   the two rules that run it.  Adding a case is a row there plus its model
   file; then [dune build @regress/smbc_models/runtest] and [dune promote] to
   refresh dune.inc.

   Columns of cases.tsv (comment lines start with '#'):
     case  model  problem  deadline  expectation

   - [model] names models/<model>.txt, replayed as smbc's stdout by
     fake_solver.
   - [problem] names problems/<problem>.nun, the problem nunchaku is asked.
   - [deadline] is the wall-clock ceiling of the whole run in seconds, or "-"
     for the default.  The deeply nested cases are the ones that carry a real
     number: decoding them used to cost time exponential in the depth, spent
     after smbc had already answered and therefore outside nunchaku's own
     --timeout, so the ceiling is the only thing that can see the regression.
     It is a run_case deadline rather than a smaller --timeout on purpose: the
     run is killed and reported as rc=timeout, which names the failure as a
     timing failure in the golden diff.
   - [expectation] is documentation, read by README.md and not by dune. *)

let default_deadline = "20"

(* nunchaku's own budget.  Every reply here is canned and instant, so this
   never fires; it is kept equal to the other suites' so a case that does hang
   hangs the same way everywhere. *)
let timeout = "5"

type case = { name : string; model : string; problem : string; deadline : string }

let read_cases file =
  let ic = open_in file in
  let rec loop acc =
    match input_line ic with
    | exception End_of_file -> close_in ic; List.rev acc
    | line ->
      let line = String.trim line in
      if line = "" || line.[0] = '#' then loop acc
      else
        (match String.split_on_char '\t' line with
         | name :: model :: problem :: deadline :: _ ->
           loop ({ name; model; problem; deadline } :: acc)
         | _ ->
           prerr_endline ("gen_dune: cannot read row: " ^ line);
           exit 2)
  in
  loop []

let pp_case c =
  let deadline = if c.deadline = "-" then default_deadline else c.deadline in
  Printf.printf
    {|
(rule
 (targets %s.out)
 (deps
  %%{exe:../support/run_case.exe}
  %%{exe:../support/fake_solver.exe}
  %%{exe:../../src/main/nunchaku.exe}
  problems/%s.nun
  models/%s.txt)
 (action
  (with-stdout-to
   %s.out
   (run
    %%{exe:../support/run_case.exe}
    --exe
    %%{exe:../../src/main/nunchaku.exe}
    --deadline
    %s
    --setenv
    "NUNCHAKU_SMBC=%%{exe:../support/fake_solver.exe}"
    --setenv
    "FAKE_REPLIES=%%{dep:models/%s.txt}"
    --
    --solvers
    smbc
    --no-color
    -j
    1
    --timeout
    %s
    %%{dep:problems/%s.nun}))))

(rule
 (alias runtest)
 (action
  (diff %s.expected %s.out)))
|}
    c.name c.problem c.model c.name deadline c.model timeout c.problem c.name
    c.name

let () =
  print_string
    "; GENERATED by gen_dune.ml from cases.tsv -- do not edit.  Add a row to\n\
     ; cases.tsv, then `dune build @regress/smbc_models/runtest` and\n\
     ; `dune promote`.\n";
  List.iter pp_case (read_cases "cases.tsv")
